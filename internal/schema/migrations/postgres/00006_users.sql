INSERT INTO chunks (
  id, doc_id, ordinal, section, page_start, page_end, printed_page_start,
  image_count, kind, url, fragment, heading_path, text)
SELECT id, doc_id, ordinal, section, page_start, page_end, printed_page_start,
       image_count, kind, url, fragment, heading_path, text
  FROM chunks_partitioned WHERE user_id = 'default';
SELECT setval(
  pg_get_serial_sequence('chunks', 'id'),
  GREATEST((SELECT COALESCE(MAX(id), 0) FROM chunks), 1));
DROP TABLE chunks_partitioned;

